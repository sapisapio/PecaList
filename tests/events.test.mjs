import assert from 'node:assert/strict';
import {eventDay,eventSchedule,eventPriority,japanDay} from '../src/events.js';
const event={event:true,name:'アスカ大会',contactUrl:'https://wikiwiki.jp/peca/%E3%82%A4%E3%83%99%E3%83%B3%E3%83%88%E6%97%A5%E7%A8%8B/2026-11-22',detail:'11月22日(日) 21:00～26:00'};
assert.equal(eventDay(event,new Date('2026-11-09T00:00:00Z')),Date.UTC(2026,10,22));
assert.equal(eventSchedule(event,new Date('2026-11-09T03:00:00Z')).label,'あと13日');
assert.equal(eventSchedule(event,new Date('2026-11-18T03:00:00Z')).soon,false);
assert.equal(eventSchedule(event,new Date('2026-11-19T03:00:00Z')).soon,true);
assert.equal(eventSchedule(event,new Date('2026-11-19T03:00:00Z')).label,'あと3日');
assert.equal(eventSchedule(event,new Date('2026-11-21T14:59:59Z')).today,false);
assert.equal(eventSchedule(event,new Date('2026-11-21T15:00:00Z')).today,true,'日本時間の0時で本日開催へ');
assert.equal(eventSchedule(event,new Date('2026-11-22T15:00:00Z')).label,'終了');
assert.equal(eventPriority(event,new Date('2026-11-22T03:00:00Z')),-1);
assert.equal(eventPriority(event,new Date('2026-11-19T03:00:00Z')),1);
assert.equal(eventPriority({event:false}),0);
assert.equal(eventDay({event:true,detail:'2028年2月29日 開催'}),Date.UTC(2028,1,29));
assert.equal(eventDay({event:true,detail:'2027/02/29 開催'}),null,'不正日付は補正せず未確認');
assert.equal(eventDay({event:true,detail:'2月30日 開催'}),null);
assert.equal(eventSchedule({event:true,detail:'未定'}).label,'日程未確認');
assert.equal(eventDay({event:true,detail:'1/5 開催'},new Date('2026-12-28T03:00:00Z')),Date.UTC(2027,0,5));
assert.equal(eventDay({event:true,detail:'12月31日'},new Date('2027-01-02T03:00:00Z')),Date.UTC(2026,11,31));
assert.equal(japanDay(new Date('2026-11-08T15:00:00Z')),Date.UTC(2026,10,9));
assert.equal(eventDay({...event,detail:'11月21日 開催'}),Date.UTC(2026,10,22),'告知URLの明示年付き日程を優先');
assert.equal(eventSchedule({event:false}).today,false);
console.log('event calendar tests ok');
